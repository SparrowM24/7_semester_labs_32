"""Порт репозитория для агрегата «Переговорная комната»."""

from __future__ import annotations

from typing import Optional, Protocol

from .aggregates import MeetingRoom

from .booking import BookingLifecycle


class MeetingRoomRepository(Protocol):
    def add(self, room: MeetingRoom) -> None: ...
    def get(self, room_id: str) -> Optional[MeetingRoom]: ...
    def save(self, room: MeetingRoom) -> None: ...

class BookingLifecycleRepository(Protocol):
    def add(self, booking: "BookingLifecycle") -> None: ...
    def get(self, booking_id: str) -> Optional["BookingLifecycle"]: ...
    def save(self, booking: "BookingLifecycle") -> None: ...
    def all(self) -> list[BookingLifecycle]: ...